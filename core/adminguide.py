def ok(ctx):
    from core.firm import ok as firm_ok
    return firm_ok(ctx)


@screen("ag")
def guide(ctx):
    if not ok(ctx):
        return Reply(text="Инструкция администратора — у владельца и администратора.")
    secs = sections(ctx)
    v = View("📘 Инструкция администратора", ctx.cfg.name)
    fb = []
    for i, s in enumerate(secs, 1):
        fb += [f"{i}. {s['t']}"] + s.get("p", []) + [f"  {j}) {x}" for j, x in enumerate(s.get("steps", []), 1)] + s.get("tail", [])
    v.ui("guide", {"items": secs, "open": 0}, "", fallback=fb)
    return Reply(view=v, buttons=[[Button("📄 Скачать PDF", "agp")], [Button("‹ Настройки", "fs")]])


def pdf_views(ctx):
    out = []
    for i, s in enumerate(sections(ctx), 1):
        v = View(f"{i}. {s['t']}", "Инструкция администратора · " + ctx.cfg.name)
        v.lines(s.get("p", []) + [f"{j}) {x}" for j, x in enumerate(s.get("steps", []), 1)] + s.get("tail", []))
        out.append(v)
    return out


@screen("agp")
def guide_pdf(ctx):
    if not ok(ctx):
        return guide(ctx)
    return Reply(text="📄 Инструкция администратора — PDF, можно переслать.",
                 files=[(f"Инструкция администратора {date.today():%d.%m.%Y}.pdf", to_pdf(pdf_views(ctx)))],
                 buttons=[[Button("📘 Инструкция", "ag")]])
